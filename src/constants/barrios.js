// Devuelve el barrio con su escritura oficial si coincide (sin importar mayúsculas ni tildes), o null.
const normalizar = (texto) =>
  texto
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .trim()
    .toLowerCase()

export const buscarBarrio = (texto) => BARRIOS_CABA.find((barrio) => normalizar(barrio) === normalizar(texto)) ?? null
